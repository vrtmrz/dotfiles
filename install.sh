#!/usr/bin/env bash

set -euo pipefail

repo_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
target="codex"
mode="install"
render_file=""
skill_src=""
skill_dst=""

usage() {
    printf '%s\n' \
        "Usage: $0 [--target codex|agy]" \
        "       $0 --render <codex|agy> <file>" \
        "       $0 --allows-target <codex|agy> <file>" \
        "       $0 --install-skill <codex|agy> <source_dir> <target_dir>" >&2
}

while [[ $# -gt 0 ]]; do
    case "$1" in
        --target)
            [[ $# -ge 2 ]] || { usage; exit 1; }
            target="$2"
            shift 2
            ;;
        --render)
            [[ $# -ge 3 ]] || { usage; exit 1; }
            mode="render"
            target="$2"
            render_file="$3"
            shift 3
            ;;
        --allows-target)
            [[ $# -ge 3 ]] || { usage; exit 1; }
            mode="allows-target"
            target="$2"
            render_file="$3"
            shift 3
            ;;
        --install-skill)
            [[ $# -ge 4 ]] || { usage; exit 1; }
            mode="install-skill"
            target="$2"
            skill_src="$3"
            skill_dst="$4"
            shift 4
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        *)
            usage
            exit 1
            ;;
    esac
done

case "$target" in
    codex|agy) ;;
    *)
        printf '%s\n' "Unsupported target: $target" >&2
        exit 1
        ;;
esac

if [[ "$target" == "codex" ]]; then
    target_dir="${CODEX_HOME:-$HOME/.codex}"
    skills_target_dir="$HOME/.agents/skills"
    guidance_target_dir="$target_dir/guidance/public"
    agents_target_dir="$target_dir/agents"
    generated_marker="<!-- Generated by dotfiles/install.sh from public and private guidance. -->"
else
    target_dir="${AGY_CONFIG_HOME:-$HOME/.gemini/config}"
    skills_target_dir="${AGY_SKILLS_HOME:-$HOME/.gemini/skills}"
    guidance_target_dir="$target_dir/guidance/public"
    agents_target_dir=""
    generated_marker="<!-- Generated by dotfiles/install4agy.sh from public and private guidance. -->"
fi
skills_backup_dir="$target_dir/backups/skills"

render_markdown() {
    local input_path="$1"
    local check_only="${2:-0}"
    python3 - "$target" "$input_path" "$check_only" <<'PY'
import re
import sys
from pathlib import Path

target = sys.argv[1]
path = Path(sys.argv[2])
check_only = sys.argv[3] == "1"

VALID_TARGETS = {"codex", "agy"}
PLACEHOLDERS = {
    "codex": {
        "{{AGENT_HOME}}": "${CODEX_HOME:-$HOME/.codex}",
        "{{GUIDANCE_ROOT}}": "${CODEX_HOME:-$HOME/.codex}/guidance",
        "{{SKILLS_ROOT}}": "~/.agents/skills",
        "{{SKILLS_SHELL_ROOT}}": "$HOME/.agents/skills",
    },
    "agy": {
        "{{AGENT_HOME}}": "~/.gemini/config",
        "{{GUIDANCE_ROOT}}": "~/.gemini/config/guidance",
        "{{SKILLS_ROOT}}": "~/.gemini/skills",
        "{{SKILLS_SHELL_ROOT}}": "$HOME/.gemini/skills",
    },
}

TARGETS_RE = re.compile(r"^\s*<!--\s*@targets:\s*([a-z0-9_,\s-]+)\s*-->\s*$")
ONLY_RE = re.compile(r"^\s*<!--\s*@only:\s*([a-z0-9_,\s-]+)\s*-->\s*$")
END_RE = re.compile(r"^\s*<!--\s*@end\s*-->\s*$")

text = path.read_text(encoding="utf-8")

if "<!-- @" not in text and "{{" not in text:
    if not check_only:
        sys.stdout.write(text)
    sys.exit(0)

def parse_targets(raw, line_no):
    items = {part.strip() for part in raw.split(",") if part.strip()}
    if not items or not items.issubset(VALID_TARGETS):
        unknown = sorted(items - VALID_TARGETS)
        raise ValueError(f"{path}:{line_no}: unknown target(s): {', '.join(unknown) or '(empty)'}")
    return items

lines = text.splitlines(keepends=True)
out = []
active_only = None
removed_any = False
skip_leading_blank = False

for index, line in enumerate(lines, start=1):
    stripped = line.rstrip("\r\n")
    m_targets = TARGETS_RE.match(stripped)
    if m_targets:
        allowed = parse_targets(m_targets.group(1), index)
        if target not in allowed:
            sys.exit(2)
        if check_only:
            sys.exit(0)
        removed_any = True
        if not out:
            skip_leading_blank = True
        continue

    if check_only:
        continue

    if skip_leading_blank and stripped == "":
        skip_leading_blank = False
        continue
    skip_leading_blank = False

    m_only = ONLY_RE.match(stripped)
    if m_only:
        if active_only is not None:
            raise ValueError(f"{path}:{index}: nested @only block is not supported")
        active_only = parse_targets(m_only.group(1), index)
        removed_any = True
        continue

    if END_RE.match(stripped):
        if active_only is None:
            raise ValueError(f"{path}:{index}: unexpected @end without @only")
        active_only = None
        removed_any = True
        continue

    if active_only is None or target in active_only:
        out.append(line)

if check_only:
    sys.exit(0)

if active_only is not None:
    raise ValueError(f"{path}: unclosed @only block")

rendered = "".join(out)
if removed_any:
    rendered = re.sub(r"\n{3,}", "\n\n", rendered)
    rendered = rendered.lstrip("\n")
    if rendered and not rendered.endswith("\n"):
        rendered += "\n"

for key, value in PLACEHOLDERS[target].items():
    rendered = rendered.replace(key, value)

sys.stdout.write(rendered)
PY
}

skill_needs_rendering() {
    local skill_dir="$1"
    python3 - "$skill_dir" <<'PY'
import sys
from pathlib import Path

root = Path(sys.argv[1])
for path in root.rglob("*.md"):
    if "__pycache__" in path.parts or ".git" in path.parts:
        continue
    text = path.read_text(encoding="utf-8")
    if "<!-- @" in text or "{{" in text:
        sys.exit(0)
sys.exit(1)
PY
}

timestamp="$(date -u +%Y%m%dT%H%M%SZ)"

preserve_existing_path() {
    local target_path="$1"
    local backup_dir="${2:-}"
    [[ -e "$target_path" || -L "$target_path" ]] || return 0

    local base_backup
    if [[ -n "$backup_dir" ]]; then
        mkdir -p "$backup_dir"
        base_backup="$backup_dir/$(basename -- "$target_path").backup.$timestamp"
    else
        base_backup="$target_path.backup.$timestamp"
    fi

    local backup_path="$base_backup"
    local suffix=1
    while [[ -e "$backup_path" || -L "$backup_path" ]]; do
        backup_path="$base_backup.$suffix"
        suffix=$((suffix + 1))
    done

    mv -- "$target_path" "$backup_path"
    printf '%s\n' "Preserved existing path: $backup_path"
}

install_link() {
    local source_path="$1"
    local target_path="$2"
    local backup_dir="${3:-}"

    if [[ -L "$target_path" ]] &&
       [[ "$(readlink -f -- "$target_path")" == "$(readlink -f -- "$source_path")" ]]; then
        printf '%s\n' "Already linked: $target_path"
        return
    fi

    preserve_existing_path "$target_path" "$backup_dir"

    ln -s -- "$source_path" "$target_path"
    printf '%s\n' "Linked: $target_path -> $source_path"
}

install_file() {
    local source_path="$1"
    local target_path="$2"

    if [[ -f "$target_path" && ! -L "$target_path" ]] &&
       cmp -s -- "$source_path" "$target_path"; then
        chmod 600 "$target_path"
        printf '%s\n' "Already installed: $target_path"
        return
    fi

    preserve_existing_path "$target_path"

    install -m 600 -- "$source_path" "$target_path"
    printf '%s\n' "Installed: $target_path"
}

install_rendered_skill() {
    local source_dir="$1"
    local target_dir_path="$2"
    local backup_dir="${3:-}"
    local stage_root
    stage_root="$(mktemp -d)"
    local stage_dir="$stage_root/skill"
    mkdir -p "$stage_dir"

    while IFS= read -r -d '' entry; do
        local rel="${entry#"$source_dir"/}"
        case "$rel" in
            */__pycache__/*|__pycache__/*|*.pyc|*/.git/*|.git/*)
                continue
                ;;
        esac
        if [[ "$target" == "agy" && "$rel" == "agents/openai.yaml" ]]; then
            continue
        fi
        local dest="$stage_dir/$rel"
        mkdir -p "$(dirname -- "$dest")"
        if [[ "$rel" == *.md ]]; then
            set +e
            render_markdown "$entry" 0 > "$dest"
            local status=$?
            set -e
            if [[ "$status" -eq 2 ]]; then
                rm -f -- "$dest"
                continue
            elif [[ "$status" -ne 0 ]]; then
                rm -rf -- "$stage_root"
                exit "$status"
            fi
            chmod 600 "$dest"
        else
            cp -p -- "$entry" "$dest"
        fi
    done < <(find "$source_dir" -type f -print0 | sort -z)

    local identical=0
    if [[ -d "$target_dir_path" && ! -L "$target_dir_path" ]]; then
        if python3 - "$stage_dir" "$target_dir_path" <<'PY'
import sys
from pathlib import Path

src = Path(sys.argv[1])
dst = Path(sys.argv[2])

def snapshot(root):
    entries = {}
    for p in sorted(root.rglob("*")):
        if p.is_symlink():
            return None
        rel = p.relative_to(root).as_posix()
        if p.is_file():
            entries[rel] = (p.stat().st_mode & 0o777, p.read_bytes())
        elif p.is_dir():
            entries[rel + "/"] = None
    return entries

s_snap = snapshot(src)
d_snap = snapshot(dst)
sys.exit(0 if s_snap is not None and s_snap == d_snap else 1)
PY
        then
            identical=1
        fi
    fi

    if [[ "$identical" -eq 1 ]]; then
        rm -rf -- "$stage_root"
        printf '%s\n' "Already installed: $target_dir_path"
        return
    fi

    preserve_existing_path "$target_dir_path" "$backup_dir"

    mkdir -p "$(dirname -- "$target_dir_path")"
    mv -- "$stage_dir" "$target_dir_path"
    rm -rf -- "$stage_root"
    printf '%s\n' "Installed: $target_dir_path"
}

install_skill() {
    local source_dir="$1"
    local dest_dir="$2"

    if [[ -f "$source_dir/SKILL.md" ]]; then
        set +e
        render_markdown "$source_dir/SKILL.md" 1
        local skill_status=$?
        set -e
        if [[ "$skill_status" -eq 2 ]]; then
            printf '%s\n' "Skipped skill ($target): $source_dir"
            return 0
        elif [[ "$skill_status" -ne 0 ]]; then
            exit "$skill_status"
        fi
    fi

    if skill_needs_rendering "$source_dir"; then
        install_rendered_skill "$source_dir" "$dest_dir" "$skills_backup_dir"
    else
        install_link "$source_dir" "$dest_dir" "$skills_backup_dir"
    fi
}

if [[ "$mode" == "render" ]]; then
    render_markdown "$render_file" 0
    exit $?
fi

if [[ "$mode" == "allows-target" ]]; then
    render_markdown "$render_file" 1
    exit $?
fi

if [[ "$mode" == "install-skill" ]]; then
    install_skill "$skill_src" "$skill_dst"
    exit 0
fi

source_file="$repo_dir/codex/AGENTS.md"
skills_source_dir="$repo_dir/codex/skills"
guidance_source_dir="$repo_dir/codex/guidance"
agents_source_dir="$repo_dir/codex/agents"

target_file="$target_dir/AGENTS.md"
private_file="$target_dir/AGENTS.private.md"
device_file="$target_dir/AGENTS.device.md"

mkdir -p "$target_dir" "$skills_target_dir" "$guidance_target_dir"
if [[ -n "$agents_target_dir" ]]; then
    mkdir -p "$agents_target_dir"
fi

if [[ -n "$agents_target_dir" ]]; then
    for agent_source in "$agents_source_dir"/*.toml; do
        [[ -f "$agent_source" ]] || continue
        install_file "$agent_source" "$agents_target_dir/$(basename -- "$agent_source")"
    done
fi

tmp_dir="$(mktemp -d)"
trap 'rm -rf -- "$tmp_dir"' EXIT

for guidance_source in "$guidance_source_dir"/*.md; do
    [[ -f "$guidance_source" ]] || continue
    rendered_detail="$tmp_dir/$(basename -- "$guidance_source")"
    set +e
    render_markdown "$guidance_source" 0 > "$rendered_detail"
    render_status=$?
    set -e
    if [[ "$render_status" -eq 2 ]]; then
        printf '%s\n' "Skipped ($target): $guidance_source"
        continue
    elif [[ "$render_status" -ne 0 ]]; then
        exit "$render_status"
    fi
    install_file "$rendered_detail" "$guidance_target_dir/$(basename -- "$guidance_source")"
done

for skill_source in "$skills_source_dir"/*; do
    [[ -d "$skill_source" ]] || continue
    install_skill "$skill_source" "$skills_target_dir/$(basename -- "$skill_source")"
done

rendered_core="$tmp_dir/AGENTS.core.md"
set +e
render_markdown "$source_file" 0 > "$rendered_core"
core_status=$?
set -e
if [[ "$core_status" -ne 0 ]]; then
    exit "$core_status"
fi

if [[ -s "$private_file" ]]; then
    temporary_file="$(mktemp "$target_dir/.AGENTS.md.XXXXXX")"
    {
        printf '%s\n\n' "$generated_marker"
        cat -- "$rendered_core"
        printf '\n\n'
        cat -- "$private_file"
        if [[ -s "$device_file" ]]; then
            printf '\n\n'
            cat -- "$device_file"
        fi
    } > "$temporary_file"

    if [[ -f "$target_file" && ! -L "$target_file" ]] && cmp -s -- "$temporary_file" "$target_file"; then
        rm -- "$temporary_file"
        printf '%s\n' "Already generated: $target_file"
        exit 0
    fi

    if [[ -e "$target_file" || -L "$target_file" ]]; then
        if [[ -L "$target_file" && "$(readlink -f -- "$target_file")" == "$(readlink -f -- "$source_file")" ]]; then
            rm -- "$target_file"
        elif [[ -f "$target_file" && ! -L "$target_file" && "$(head -n 1 -- "$target_file")" == "$generated_marker" ]]; then
            rm -- "$target_file"
        else
            backup_file="$target_file.backup.$(date -u +%Y%m%dT%H%M%SZ)"
            mv -- "$target_file" "$backup_file"
            printf '%s\n' "Preserved existing file: $backup_file"
        fi
    fi

    mv -- "$temporary_file" "$target_file"
    chmod 600 "$target_file"
    printf '%s\n' "Generated: $target_file from $source_file and $private_file"
    exit 0
fi

if [[ "$target" == "codex" ]] && cmp -s -- "$rendered_core" "$source_file"; then
    if [[ -e "$target_file" || -L "$target_file" ]]; then
        if [[ "$(readlink -f -- "$target_file")" == "$(readlink -f -- "$source_file")" ]]; then
            printf '%s\n' "Already linked: $target_file"
            exit 0
        fi

        backup_file="$target_file.backup.$(date -u +%Y%m%dT%H%M%SZ)"
        mv -- "$target_file" "$backup_file"
        printf '%s\n' "Preserved existing file: $backup_file"
    fi

    ln -s -- "$source_file" "$target_file"
    printf '%s\n' "Linked: $target_file -> $source_file"
    exit 0
fi

install_file "$rendered_core" "$target_file"
